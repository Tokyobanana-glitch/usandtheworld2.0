-- ---------------------------------------------------------------------------
-- Storage — passport photos
-- ---------------------------------------------------------------------------

-- Private bucket: RLS on storage.objects (below) is what actually restricts
-- access, but public=false also blocks the unauthenticated public-URL path
-- entirely, so a leaked object path alone is never enough to view a photo.
insert into storage.buckets (id, name, public)
values ('passport-photos', 'passport-photos', false)
on conflict (id) do nothing;

-- Upload path convention: <user_id>/<filename> — storage.foldername(name)
-- splits the object path on "/" and returns the folder segments, so
-- (storage.foldername(name))[1] is that leading <user_id> segment. A user
-- can only touch objects under their own folder; nobody can list or read
-- another user's photos, matching the private-by-default posture on the
-- tables above (unlike creator_clips, which is deliberately public).
drop policy if exists "passport photos select own" on storage.objects;
create policy "passport photos select own" on storage.objects for select using (
  bucket_id = 'passport-photos' and (storage.foldername(name))[1] = auth.uid()::text
);
drop policy if exists "passport photos insert own" on storage.objects;
create policy "passport photos insert own" on storage.objects for insert with check (
  bucket_id = 'passport-photos' and (storage.foldername(name))[1] = auth.uid()::text
);
drop policy if exists "passport photos update own" on storage.objects;
create policy "passport photos update own" on storage.objects for update using (
  bucket_id = 'passport-photos' and (storage.foldername(name))[1] = auth.uid()::text
);
drop policy if exists "passport photos delete own" on storage.objects;
create policy "passport photos delete own" on storage.objects for delete using (
  bucket_id = 'passport-photos' and (storage.foldername(name))[1] = auth.uid()::text
);
